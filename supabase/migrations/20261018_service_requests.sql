create table if not exists public.service_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  requester_name text not null check (char_length(requester_name) between 2 and 100),
  email text not null check (char_length(email) between 5 and 254),
  organization text,
  service_type text not null check (service_type in (
    'free-demo',
    'one-to-one-mentoring',
    'career-guidance',
    'interview-preparation',
    'ai-course',
    'corporate-training',
    'corporate-ai-it-support'
  )),
  preferred_date date,
  preferred_time text,
  timezone text not null default 'Asia/Kolkata',
  meeting_provider text not null default 'Google Meet',
  message text not null check (char_length(message) between 10 and 2000),
  status text not null default 'new' check (status in ('new', 'contacted', 'scheduled', 'closed')),
  created_at timestamptz not null default now()
);

create index if not exists service_requests_user_id_idx on public.service_requests (user_id, created_at desc);
create index if not exists service_requests_status_idx on public.service_requests (status, created_at desc);

alter table public.service_requests enable row level security;

grant insert, select on public.service_requests to authenticated;
grant usage, select on sequence public.service_requests_id_seq to authenticated;

drop policy if exists "Users can create their own service requests" on public.service_requests;
create policy "Users can create their own service requests"
  on public.service_requests
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users can view their own service requests" on public.service_requests;
create policy "Users can view their own service requests"
  on public.service_requests
  for select
  to authenticated
  using ((select auth.uid()) = user_id);
