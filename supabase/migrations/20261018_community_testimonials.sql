create table if not exists public.testimonials (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 2 and 80),
  role_label text not null check (char_length(role_label) between 2 and 120),
  outcome text not null check (char_length(outcome) between 2 and 160),
  body text not null check (char_length(body) between 30 and 1200),
  avatar_url text,
  consent_public boolean not null default false,
  status text not null default 'published' check (status in ('published', 'hidden')),
  created_at timestamptz not null default now()
);

create index if not exists testimonials_status_created_at_idx on public.testimonials (status, created_at desc);

alter table public.testimonials enable row level security;

grant select on public.testimonials to anon, authenticated;
grant insert, update, delete on public.testimonials to authenticated;
grant usage, select on sequence public.testimonials_id_seq to authenticated;

drop policy if exists "Public published testimonials" on public.testimonials;
create policy "Public published testimonials"
  on public.testimonials for select
  to anon, authenticated
  using (status = 'published' and consent_public = true);

drop policy if exists "Users can publish their own testimonial" on public.testimonials;
create policy "Users can publish their own testimonial"
  on public.testimonials for insert
  to authenticated
  with check (
    (select auth.uid()) = user_id
    and consent_public = true
    and status = 'published'
  );

drop policy if exists "Users can edit their own testimonial" on public.testimonials;
create policy "Users can edit their own testimonial"
  on public.testimonials for update
  to authenticated
  using ((select auth.uid()) = user_id)
  with check (
    (select auth.uid()) = user_id
    and consent_public = true
    and status = 'published'
  );

drop policy if exists "Users can remove their own testimonial" on public.testimonials;
create policy "Users can remove their own testimonial"
  on public.testimonials for delete
  to authenticated
  using ((select auth.uid()) = user_id);
