create table if not exists users (
  id bigint generated by default as identity primary key,
  email text unique not null,
  name text,
  avatar_url text,
  role text not null default 'buyer',
  hashed_password text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists products (
  id bigint generated by default as identity primary key,
  seller_id bigint references users(id) on delete set null,
  slug text unique not null,
  title text not null,
  category text not null,
  short_description text,
  description text,
  price numeric(10,2) not null default 0,
  is_free boolean not null default false,
  status text not null default 'draft',
  created_at timestamptz not null default now()
);

create table if not exists plans (
  id bigint generated by default as identity primary key,
  name text unique not null,
  price numeric(10,2) not null default 0,
  interval text not null default 'month',
  trial_days integer not null default 0,
  features jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists subscriptions (
  id bigint generated by default as identity primary key,
  user_id bigint references users(id) on delete cascade,
  product_id bigint references products(id) on delete cascade,
  plan_name text not null default 'starter',
  status text not null default 'active',
  stripe_subscription_id text,
  current_period_end timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists licenses (
  id bigint generated by default as identity primary key,
  user_id bigint references users(id) on delete cascade,
  product_id bigint references products(id) on delete cascade,
  license_key text unique not null,
  status text not null default 'active',
  expires_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists reviews (
  id bigint generated by default as identity primary key,
  product_id bigint references products(id) on delete cascade,
  user_id bigint references users(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  comment text,
  created_at timestamptz not null default now()
);

create index if not exists idx_products_slug on products(slug);
create index if not exists idx_products_category on products(category);
create index if not exists idx_products_status on products(status);
create index if not exists idx_products_created_at on products(created_at desc);
create index if not exists idx_reviews_product_id on reviews(product_id);

alter table products enable row level security;
alter table plans enable row level security;
drop policy if exists "public approved products" on products;
create policy "public approved products" on products for select to anon, authenticated using (status = 'approved');
drop policy if exists "public plans" on plans;
create policy "public plans" on plans for select to anon, authenticated using (true);
