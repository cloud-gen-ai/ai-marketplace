create table if not exists public.activity_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_type text not null check (event_type ~ '^[a-z][a-z0-9_]{1,48}$'),
  title text not null check (char_length(title) between 2 and 160),
  description text check (description is null or char_length(description) <= 500),
  resource_type text,
  resource_slug text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_activity_events_user_created
  on public.activity_events(user_id, created_at desc);

create index if not exists idx_activity_events_resource
  on public.activity_events(resource_type, resource_slug);

alter table public.activity_events enable row level security;

grant select, insert on table public.activity_events to authenticated;
grant usage, select on sequence public.activity_events_id_seq to authenticated;

drop policy if exists "Users can view their own activity" on public.activity_events;
create policy "Users can view their own activity"
  on public.activity_events
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Users can record their own activity" on public.activity_events;
create policy "Users can record their own activity"
  on public.activity_events
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);
